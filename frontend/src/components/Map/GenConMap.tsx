// ── Purchased event (from user_events API) ───────────────────────────────────
interface PurchasedEvent {
  id: number;
  event_title: string;
  event_game_id: string;
  event_location: string;
  event_room: string | null;
  event_start_time: string;
  // Room-level Gen Con map coords (precise, floor-specific)
  room_map_lng: number | null;
  room_map_lat: number | null;
  room_map_floor: number | null;
  // Location-level real-world coords (building fallback, no floor)
  event_longitude: number | null;
  event_latitude: number | null;
  status: string;
}

// Resolve the best available coordinates for a purchased event.
// Returns { lng, lat, floorSpecific } — floorSpecific=false means show on all floors.
function resolveEventCoords(ev: PurchasedEvent): { lng: number; lat: number; floor: number | null } | null {
  if (ev.room_map_lng != null && ev.room_map_lat != null) {
    return { lng: ev.room_map_lng, lat: ev.room_map_lat, floor: ev.room_map_floor };
  }
  if (ev.event_longitude != null && ev.event_latitude != null) {
    return { lng: ev.event_longitude, lat: ev.event_latitude, floor: null }; // null = show on all floors
  }
  return null;
}

// ── Per-zoom actual image dimensions [width, height] ────────────────────────
// Generated by stitch_images.py from CloudFront tiles (256px each):
//   z3: 8×8 tiles   → 2048×2048
//   z4: 16×16       → 4096×4096
//   z5: 32×32       → 8192×8192
//   z6: 64×51 tiles → 16384×13056
//   z7: 128×65 tiles→ 32768×16640
const IMAGE_DIMS: Record<number, [number, number]> = {
  3: [2048, 2048],
  4: [4096, 4096],
  5: [8192, 8192],
  6: [16384, 13056],
  7: [32768, 16640],
};

// Vendor map_x = longitude (−180 to +180) and map_y = latitude (−85.051 to
// +85.051) in Web Mercator geographic coordinates, confirmed by the
// geo_elements API corner requests: the full floor-1 map spans exactly the
// Web Mercator world limits.
//
// Pixel conversion uses Web Mercator projection (NOT linear):
//   pixel_x = (lng + 180) / 360 × imgW
//   pixel_y = (1 − ln(tan(π/4 + lat_rad/2)) / π) / 2 × imgW
//
// imgW (= 2^z × 256) is the full-world pixel width at every zoom level.
// imgH may be truncated at z6-z7 (southern hemisphere tiles absent), so we
// always use imgW as the Mercator world extent for both axes.
//
// Leaflet CRS.Simple: lng_leaflet = pixel_x; lat_leaflet = −pixel_y.

