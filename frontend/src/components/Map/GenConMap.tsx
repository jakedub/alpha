// ── Auto-resolution thresholds ───────────────────────────────────────────────
// When Leaflet zoom >= UPGRADE_AT[imageZoom], bump imageZoom up one step.
// When Leaflet zoom <= DOWNGRADE_AT[imageZoom], drop imageZoom down one step.
// Hysteresis gap prevents thrashing at the boundary.
const UPGRADE_AT: Partial<Record<number, number>> = { 3: 0, 4: 1, 5: 2, 6: 3 };
const DOWNGRADE_AT: Partial<Record<number, number>> = { 4: -3, 5: -2, 6: -1, 7: 0 };

// Integer zoom steps offered in the Map Zoom dropdown
const MAP_ZOOM_STEPS = [-6, -5, -4, -3, -2, -1, 0, 1, 2, 3, 4];

// ── Shared Web Mercator → Leaflet coordinate conversion ─────────────────────
function toLeafletPos(lng: number, lat: number, imgW: number): [number, number] {
  const lat_rad = lat * Math.PI / 180;
  const yMercator = Math.log(Math.tan(Math.PI / 4 + lat_rad / 2));
  const pixelY = (1 - yMercator / Math.PI) / 2 * imgW;
  const pixelX = (lng + 180) / 360 * imgW;
  return [-pixelY, pixelX];
}

// ── Convert a booth polygon [[lng, lat], ...] to Leaflet positions ───────────
function toLeafletPolygon(polygon: [number, number][], imgW: number): [number, number][] {
  return polygon.map(([lng, lat]) => toLeafletPos(lng, lat, imgW));
}

// ── Inverse Web Mercator: Leaflet pixel coords → Gen Con map lng/lat ─────────
// Leaflet CRS.Simple gives us pixel coords as [lat=-pixelY, lng=pixelX].
// Reverse the projection to recover Gen Con map_x (lng) and map_y (lat).
function fromLeafletPos(leafletLat: number, leafletLng: number, imgW: number) {
  const pixelX = leafletLng;
  const pixelY = -leafletLat;
  const gencon_lng = pixelX / imgW * 360 - 180;
  const mercatorY = Math.PI * (1 - 2 * pixelY / imgW);
  const gencon_lat = (2 * Math.atan(Math.exp(mercatorY)) - Math.PI / 2) * 180 / Math.PI;
  return { gencon_lng, gencon_lat };
}

// ── Route types ──────────────────────────────────────────────────────────────
interface RouteNode { node_id: string; label: string; }
interface RouteSegment {
  from_label: string; to_label: string;
  from_lng: number;   from_lat: number;
  to_lng: number;     to_lat: number;
  edge_type: 'indoor' | 'outdoor' | string;
  metres: number;
}
interface RouteResult {
  from_node: string; to_node: string;
  total_metres: number;
  segments: RouteSegment[];
}

// ── Combined map event handler ───────────────────────────────────────────────
// Handles coordinate picking, zoom/move tracking, and view restoration after
// imageZoom-triggered remounts.
interface PickResult { gencon_lng: number; gencon_lat: number; }

function MapEventHandler({
  active,
  imgW,
  onPick,
  onMapChange,
  mapRef,
  savedViewRef,
}: {
  active: boolean;
  imgW: number;
  onPick: (r: PickResult) => void;
  onMapChange: (zoom: number, center: [number, number]) => void;
  mapRef: React.MutableRefObject<L.Map | null>;
  savedViewRef: React.MutableRefObject<{ gencon_lng: number; gencon_lat: number; zoom: number } | null>;
}) {
  const map = useMap();

  // On mount: store map ref and restore saved position if present.
  // Empty deps intentional — runs once per MapContainer lifecycle.
  useEffect(() => {
    mapRef.current = map;
    const sv = savedViewRef.current;
    if (sv) {
      savedViewRef.current = null;
      const [lat, lng] = toLeafletPos(sv.gencon_lng, sv.gencon_lat, imgW);
      map.setView([lat, lng], sv.zoom, { animate: false });
    }
    return () => { mapRef.current = null; };
  }, []); // eslint-disable-line react-hooks/exhaustive-deps

  useMapEvents({
    click(e) {
      if (!active) return;
      const result = fromLeafletPos(e.latlng.lat, e.latlng.lng, imgW);
      onPick(result);
    },
    zoomend() {
      onMapChange(map.getZoom(), [map.getCenter().lat, map.getCenter().lng]);
    },
    moveend() {
      onMapChange(map.getZoom(), [map.getCenter().lat, map.getCenter().lng]);
    },
  });
  return null;
}

